// The CopilotKit endpoint: transport and UI protocol for the assistant, and the in-process
// invocation the summary cards run through.
//
// CopilotKit supplies the wire. It does not supply the brain. Every Tamandua answer still comes from
// `assistant.run()` (src/assistant/agent.js), which owns tool activity tracking, the MCP connection, the
// decrypted token and the SQLite history — the assistant's data handling and activity guarantees
// live there and are translated into AG-UI events by aguiBridge.js, not re-implemented here.
// Adapters stay separate from UI, and the MCP server's safety
// semantics unchanged.
//
// Nothing in this file may put record data into a thread message: a thread's events are readable by
// whatever else is bound to 127.0.0.1, which is the whole reason the summaries are generated by a
// server-side runLocal rather than by a chat the browser can replay.

// Telemetry is on by default: the runtime constructor fires one event, and each run sends more, to
// https://telemetry.copilotkit.ai/ingest. That contradicts README.md ("No cloud account, telemetry, or
// analytics are configured") and it is a network call out of an app whose selling point is that the
// records never leave the machine. The documented kill switch is these two variables, and the library
// re-reads them on every send (dist/v2/runtime/telemetry/telemetry-client.cjs:62), not just at startup.
// Set them here, before the library is required, so the default holds in `npm test` as well as under
// server.js — which loads .env only after requiring src/app. Only when unset, so an operator who wants
// telemetry on can still turn it on with a real environment variable.
if (process.env.COPILOTKIT_TELEMETRY_DISABLED === undefined) process.env.COPILOTKIT_TELEMETRY_DISABLED = '1';
if (process.env.DO_NOT_TRACK === undefined) process.env.DO_NOT_TRACK = '1';

const { CopilotRuntime, BuiltInAgent, InMemoryAgentRunner, createCopilotRuntimeHandler } = require('@copilotkit/runtime/v2');
const { createCopilotExpressHandler } = require('@copilotkit/runtime/v2/express');
const { EventType } = require('@ag-ui/core');

const COPILOT_BASE_PATH = '/api/copilotkit';

// An error that carries the AG-UI RUN_ERROR code so the caller can branch on it. `sanitizeError` has
// already stripped credentials from the message before it reaches this stream.
//
// `status` is the HTTP status when the failure came from one — the policy gate answers 428 (§C) and the
// route that surfaces it to the user has to be able to answer 428 too rather than turning "you have not
// accepted the disclosure" into a generic bad-gateway.
class CopilotRunError extends Error {
  constructor(message, code, status) {
    super(message);
    this.name = 'CopilotRunError';
    this.code = code || 'agent_run_failed';
    if (status) this.status = status;
  }
}

// The stand-in agent, registered as `echo` and NOT as `tamandua`. It exists so the transport can be
// tested without a model endpoint: echoed text, never records. The real surfaces arrive through
// `extraAgents` below — copilotAgents.js registers `tamandua` (the chat, over `assistant.run()` + the
// bridge) and later `summary` (the cards).
//
// Keeping the stand-in off the `tamandua` name is deliberate: if the app ever fails to register the real
// agent, a request should answer "no such agent", not get a polite echo that looks like an answer.
// `forwardedProps` is echoed because the summary agent reads {placement, period} out of it, and whether
// it reaches the factory at all is a thing a test has to know rather than assume.
async function* echoFactory(ctx) {
  const props = ctx.input.forwardedProps || {};
  const asked = ctx.input.messages.filter((m) => m.role === 'user').pop();
  yield { type: EventType.TEXT_MESSAGE_START, messageId: 'tamandua-echo', role: 'assistant' };
  yield {
    type: EventType.TEXT_MESSAGE_CONTENT,
    messageId: 'tamandua-echo',
    delta: `echo:${asked ? asked.content : ''}|props:${JSON.stringify(props)}`,
  };
  yield { type: EventType.TEXT_MESSAGE_END, messageId: 'tamandua-echo' };
}

// `hooks` are the ones both entry points must obey — see the note on endpointOptions below.
// `extraAgents` extends or replaces the registry: the bridge registers the real `tamandua` agent
// through it, and a test can mount a scripted agent. It is called per request, like the registry
// above, and spread last on purpose — an override is the point. Nothing outside this process can add
// an agent, because the registry is only ever built here.
function createCopilotModule({ hooks, extraAgents } = {}) {
  const runtime = new CopilotRuntime({
    // Threads live in memory only. Our SQLite `assistant_conversations` table is the history the user
    // sees, deletes and backs up (FR-10); CopilotKit's thread store is scratch state for one server
    // process and dies with it. @copilotkit/sqlite-runner is deliberately not used: it would create
    // its own tables inside data/portfolio.sqlite, the file backup and restore operate on.
    //
    // `supersede` is load-bearing, not a preference. Measured against 1.85.0: when a browser drops the
    // connection mid-run (tab closed, Stop pressed), the server-side generator does get its abort
    // signal but often finishes against a dead writer, and the default `throw` leaves the thread
    // locked — the next question in the same conversation answers RUN_ERROR(THREAD_ALREADY_RUNNING)
    // and stays locked until an explicit agent/stop. Supersede makes the new run evict the old one,
    // which is the behaviour a single-user local app wants: the newest question wins.
    runner: new InMemoryAgentRunner({ onConcurrentRun: 'supersede' }),
    // A factory, not a static map: a conversation needs the token decrypted for *this* request, and an
    // agent built once at startup would either hold the plaintext or hold nothing.
    agents: async () => ({
      echo: new BuiltInAgent({ type: 'custom', factory: echoFactory }),
      ...(extraAgents ? await extraAgents() : {}),
    }),
  });

  // Two entry points onto the same runtime, built from ONE options object. The express router serves
  // the browser; the fetch handler serves runLocal. They must share configuration — a policy hook that
  // guards the browser route while the local route skips it is not a gate — so neither is constructed
  // with a private copy of these settings.
  const endpointOptions = {
    runtime,
    basePath: COPILOT_BASE_PATH,
    // One URL for everything: the app then has one thing to gate and one thing to test, and the SPA
    // catch-all in src/app.js cannot shadow a second route shape.
    mode: 'single-route',
    // Same-origin only. `cors: true` is the library default and answers `origin: "*"`, which would let
    // any page the user visits read their assistant threads over the loopback bind.
    cors: false,
    // No long-running channel work: this app serves one person on their own machine.
    activateChannels: false,
    ...(hooks ? { hooks } : {}),
  };
  const router = createCopilotExpressHandler(endpointOptions);
  const handler = createCopilotRuntimeHandler(endpointOptions);

  return { router, handler, runtime, runLocal: runLocalFor(handler) };
}

// Splits an SSE body into parsed events. Frames are `data: {json}` separated by a blank line; anything
// else in the stream (keep-alive comments, the `[DONE]` sentinel) is skipped rather than thrown on.
function eventsFromSse(text) {
  return text.split('\n\n')
    .filter((frame) => frame.startsWith('data:'))
    .map((frame) => {
      try { return JSON.parse(frame.slice('data:'.length).trim()); } catch { return null; }
    })
    .filter(Boolean);
}

// Runs an agent against this process's own runtime without opening a socket, and returns the answer as
// text. This is how a summary card gets its model call: the card needs a completion, 1.85.0 has no
// headless client API for the browser, and doing it here keeps the records snapshot out of any thread
// the browser can read. `agentId: "summary"` never appears in the browser's agent list.
function runLocalFor(handler) {
  return async function runLocal({ agentId, threadId, message = '', forwardedProps = {}, signal } = {}) {
    if (!agentId) throw new Error('runLocal needs an agentId');
    if (!threadId) throw new Error('runLocal needs a threadId — the runtime keys its in-memory state on it');
    const response = await handler(new Request(`http://127.0.0.1${COPILOT_BASE_PATH}`, {
      method: 'POST',
      headers: { 'content-type': 'application/json', accept: 'text/event-stream' },
      body: JSON.stringify({
        method: 'agent/run',
        params: { agentId },
        body: {
          threadId: String(threadId),
          runId: `local-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
          tools: [],
          context: [],
          state: {},
          forwardedProps,
          messages: message ? [{ id: `local-message`, role: 'user', content: message }] : [],
        },
      }),
      ...(signal ? { signal } : {}),
    }));

    const raw = await response.text();
    const events = eventsFromSse(raw);
    const failure = events.find((event) => event.type === EventType.RUN_ERROR);
    if (!response.ok && !failure) {
      // A non-2xx with no events in it is a refusal made before the run started — the policy gate answers
      // 428 JSON for exactly that (copilotAgents.js). Lifting its `code` is what lets a caller tell "the
      // disclosure has not been accepted" from "the endpoint is broken", which is the difference between
      // opening a modal and retrying; flattening both into one error is how a gate becomes invisible.
      let refusal = null;
      try { refusal = JSON.parse(raw); } catch { /* not JSON: fall through to the status line */ }
      throw new CopilotRunError(refusal?.error || `The assistant endpoint answered ${response.status}.`,
        refusal?.code || 'endpoint_error', response.status);
    }
    if (failure) throw new CopilotRunError(failure.message || 'The run failed.', failure.code);

    return {
      text: events.filter((event) => event.type === EventType.TEXT_MESSAGE_CONTENT).map((event) => event.delta).join(''),
      events,
    };
  };
}

module.exports = { createCopilotModule, runLocalFor, eventsFromSse, CopilotRunError, COPILOT_BASE_PATH, echoFactory };
